const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
let browser;

(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:5173');
  await page.getByText('MOCK MODE · NO API COST').waitFor();
  await page.screenshot({ path: 'artifacts/ui-home.png', fullPage: true });
  await page.getByLabel('What would you like to establish?').fill('When was the Eiffel Tower completed and where is it located?');
  await page.getByText('Add context or a document').click();
  await page.getByLabel('Supporting text').fill('The Eiffel Tower was completed in 1889. The Eiffel Tower is located in Paris.');
  await page.getByRole('button', { name: 'Run consensus' }).click();
  await page.getByRole('tab', { name: 'Claims', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'Claims', exact: true }).click();
  await page.locator('.claim-card').first().waitFor();
  await page.screenshot({ path: 'artifacts/ui-claims.png', fullPage: true });
  await page.getByRole('tab', { name: 'Agreement map' }).click();
  await page.locator('.claim-graph').waitFor();
  await page.screenshot({ path: 'artifacts/ui-graph.png', fullPage: true });
  await page.getByRole('tab', { name: 'Human review' }).click();
  const wrong = page.locator('.review-card').filter({ hasText: '1888' }).first();
  await wrong.getByLabel('Action').selectOption('CORRECT');
  await wrong.getByLabel('Corrected claim').fill('The Eiffel Tower was completed in 1889.');
  await wrong.getByLabel('Reviewer').fill('Browser smoke test reviewer');
  await wrong.getByLabel('Reason').fill('Development fixture correction; not a real human validation.');
  await wrong.getByRole('button', { name: 'Save review' }).click();
  await wrong.getByText('Review saved.', { exact: false }).waitFor();
  await page.getByRole('tab', { name: 'Conclusion', exact: true }).click();
  await page.getByRole('button', { name: 'Run again with current validated memory' }).click();
  await page.getByRole('button', { name: 'Run consensus' }).waitFor();
  await page.getByRole('tab', { name: 'Knowledge used' }).waitFor();
  await page.getByRole('tab', { name: 'Knowledge used' }).click();
  await page.getByText('Human-validated memory · version 2').first().waitFor();
  await page.screenshot({ path: 'artifacts/ui-memory.png', fullPage: true });
  await page.getByRole('button', { name: 'New council conversation' }).click();
  await page.getByPlaceholder('Ask your question...', { exact: false }).fill('When was the Eiffel Tower completed?');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await page.getByText('Stage 3: Final Council Answer').waitFor();
  await page.getByRole('button', { name: 'Consensus engine', exact: true }).click();
  await page.setViewportSize({ width: 600, height: 900 });
  await page.screenshot({ path: 'artifacts/ui-mobile.png', fullPage: true });
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Browser smoke passed: claims, graph, review/correction, future memory, original council SSE; no page errors.');
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
